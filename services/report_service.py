"""Create portable release-decision reports for audit and sharing."""

import csv
import io
import json
from datetime import datetime, timezone
from html import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    KeepTogether,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


def assessment_payload(result: dict, approval: dict | None = None) -> dict:
    """Return a stable, serialisable decision record."""
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "run": result["run_metadata"],
        "release": {
            "name": result["release"].get("release"),
            "target_date": result["release"].get("target_date"),
            "owner": result["release"].get("owner"),
        },
        "assessment": result["assessment"],
        "agent_analyses": result["analyses"],
        "pipeline": result["pipeline"],
        "human_approval": approval,
    }


def build_json_report(result: dict, approval: dict | None = None) -> bytes:
    return json.dumps(
        assessment_payload(result, approval), indent=2, ensure_ascii=False
    ).encode("utf-8")


def build_csv_report(result: dict) -> bytes:
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["Risk factor", "Actual points", "Maximum points", "Utilisation"])
    assessment = result["assessment"]
    for factor, score in assessment["factors"].items():
        maximum = assessment["max_factors"][factor]
        utilisation = score / maximum if maximum else 0
        writer.writerow([factor, score, maximum, f"{utilisation:.0%}"])
    writer.writerow([])
    writer.writerow(["Overall score", assessment["score"], 100, assessment["level"]])
    writer.writerow(["Recommendation", assessment["recommendation"]])
    return output.getvalue().encode("utf-8")


def build_html_report(result: dict, approval: dict | None = None) -> bytes:
    release = result["release"]
    assessment = result["assessment"]
    risks = "".join(f"<li>{escape(item)}</li>" for item in assessment["top_risks"])
    actions = "".join(
        f"<li>{escape(item)}</li>" for item in assessment["recommended_actions"]
    )
    factors = "".join(
        f"<tr><td>{escape(name)}</td><td>{score}</td>"
        f"<td>{assessment['max_factors'][name]}</td></tr>"
        for name, score in assessment["factors"].items()
    )
    approval_html = (
        f"<p><strong>{escape(approval['decision'])}</strong><br>"
        f"Approver: {escape(approval['approver'])}<br>"
        f"Rationale: {escape(approval['reason'])}</p>"
        if approval
        else "<p>Pending human approval.</p>"
    )
    html = f"""<!doctype html>
<html><head><meta charset="utf-8"><title>Release Guardian Report</title>
<style>
body{{font:15px Arial,sans-serif;color:#172033;max-width:900px;margin:40px auto;line-height:1.5}}
.header{{padding:28px;background:#101728;color:white;border-radius:12px}}
.decision{{margin:24px 0;padding:22px;border-left:8px solid {assessment['colour']};background:#f5f7fb}}
.score{{font-size:44px;font-weight:800}} table{{border-collapse:collapse;width:100%}}
th,td{{padding:10px;border-bottom:1px solid #ddd;text-align:left}} h2{{margin-top:30px}}
@media print{{body{{margin:15mm}} .header{{print-color-adjust:exact}}}}
</style></head><body>
<div class="header"><small>A³R³ · RELEASE DECISION RECORD</small>
<h1>{escape(str(release.get('release', 'Release')))}</h1>
<p>Target {escape(str(release.get('target_date', 'Not set')))} ·
Owner {escape(str(release.get('owner', 'Not set')))}</p></div>
<div class="decision"><div class="score">{assessment['score']}/100</div>
<strong>{escape(assessment['level'])} RISK · {escape(assessment['recommendation'])}</strong>
<p>{escape(assessment['summary'])}</p></div>
<h2>Why</h2><ul>{risks}</ul>
<h2>Recommended actions</h2><ol>{actions}</ol>
<h2>Risk contribution</h2><table><tr><th>Factor</th><th>Actual points</th><th>Maximum points</th></tr>{factors}</table>
<h2>Human decision</h2>{approval_html}
<p><small>Run {escape(result['run_metadata']['run_id'])} · Generated by AI Release Guardian.
Risk scoring is deterministic; release authority remains human.</small></p>
</body></html>"""
    return html.encode("utf-8")


def build_pdf_report(result: dict, approval: dict | None = None) -> bytes:
    buffer = io.BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=16 * mm,
        title=f"{result['release'].get('release', 'Release')} readiness report",
    )
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(
        name="Decision",
        parent=styles["Heading1"],
        alignment=TA_CENTER,
        textColor=colors.HexColor(result["assessment"]["colour"]),
        fontSize=20,
        leading=25,
        spaceAfter=8,
    ))
    assessment = result["assessment"]
    analyses = result["analyses"]
    story = [
        Paragraph("AI RELEASE GUARDIAN", styles["Title"]),
        Paragraph(
            escape(str(result["release"].get("release", "Release readiness"))),
            styles["Heading2"],
        ),
        Paragraph(
            f"Run {escape(result['run_metadata']['run_id'])} · "
            f"Target {escape(str(result['release'].get('target_date', 'Not set')))}",
            styles["Normal"],
        ),
        Spacer(1, 8 * mm),
        Paragraph(
            f"{assessment['score']}/100 · {assessment['level']} RISK · "
            f"{assessment['recommendation']}",
            styles["Decision"],
        ),
        Paragraph(escape(assessment["summary"]), styles["BodyText"]),
        Spacer(1, 5 * mm),
    ]
    kpis = [
        ["Jira stories", "WDIO tests run", "WDIO failures", "Critical/High defects"],
        [
            analyses["requirements"]["story_count"],
            analyses["regression"]["executed"],
            analyses["regression"]["failed"],
            analyses["defects"].get(
                "blocker_count",
                analyses["defects"].get("critical_count", 0)
                + analyses["defects"].get("high_count", 0),
            ),
        ],
    ]
    kpi_table = Table(kpis, colWidths=[40 * mm] * 4)
    kpi_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#172033")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#DDE2EB")),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.extend([kpi_table, Spacer(1, 6 * mm)])

    def bullet_section(title: str, items: list[str]):
        content = [Paragraph(title, styles["Heading2"])]
        content.extend(
            Paragraph(f"• {escape(item)}", styles["BodyText"]) for item in items
        )
        content.append(Spacer(1, 4 * mm))
        return KeepTogether(content)

    story.append(bullet_section("Top risks", assessment["top_risks"]))
    story.append(bullet_section("Recommended actions", assessment["recommended_actions"]))
    story.append(Paragraph("Risk contribution", styles["Heading2"]))
    factor_rows = [["Factor", "Actual points", "Maximum points"]] + [
        [name, score, assessment["max_factors"][name]]
        for name, score in assessment["factors"].items()
    ]
    factor_table = Table(factor_rows, colWidths=[95 * mm, 30 * mm, 30 * mm])
    factor_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E9EDFF")),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#DDE2EB")),
        ("ALIGN", (1, 1), (-1, -1), "CENTER"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.extend([factor_table, Spacer(1, 6 * mm)])
    story.append(Paragraph("Human decision", styles["Heading2"]))
    if approval:
        story.append(Paragraph(
            f"{escape(approval['decision'])}<br/>Approver: "
            f"{escape(approval['approver'])}<br/>Rationale: "
            f"{escape(approval['reason'])}",
            styles["BodyText"],
        ))
    else:
        story.append(Paragraph("Pending human approval.", styles["BodyText"]))
    document.build(story)
    return buffer.getvalue()
